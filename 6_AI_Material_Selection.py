# 1.  PbTe MATERIAL PROPERTIES  (at ~600 K)
# ─────────────────────────────────────────────────────────────────
S_n   = -200e-6   # Seebeck coefficient n-type [V/K]  (Iodine doped)
S_p   = +240e-6   # Seebeck coefficient p-type [V/K]  (Sodium doped)
sig_n = 100_000   # Electrical conductivity n-type [S/m]
