# ─────────────────────────────────────────────────────────────────
# 2.  PHYSICS-BASED TEG FORWARD MODEL
#     Single thermocouple: one n-leg + one p-leg connected by
#     a copper interconnect, sandwiched between quartz glass.
# ─────────────────────────────────────────────────────────────────
def teg_model(H_TE, H_IC, FF, W_n, W_p, rho_C, T_h):
    """
    Analytical forward model for a single thermocouple TEG.

    Parameters
    ----------
    H_TE  : float   Leg height [m]
    H_IC  : float   Copper interconnect height [m]
    FF    : float   Fill factor (0 to 1)
    W_n   : float   N-leg width [m]
    W_p   : float   P-leg width [m]
    rho_C : float   Contact resistivity [Omega·m^2]
    T_h   : float   Hot-side temperature [K]

    Returns
    -------
    PD_max : float   Maximum power density [mW/cm^2]
    eta    : float   Efficiency [%]
    """
    A_n = W_n**2            # cross-sectional area, n-leg [m^2]
    A_p = W_p**2            # cross-sectional area, p-leg [m^2]
    # Device footprint derived from leg widths and fill factor
    A_device = (W_n + W_p)**2 / max(FF, 1e-3)

    # Electrical resistances [Omega]
    R_n  = H_TE / (sig_n * A_n)                   # n-leg
    R_p  = H_TE / (sig_p * A_p)                   # p-leg
    R_IC = H_IC / (6e7 * (W_n + W_p)**2)          # Cu interconnect (sigma_Cu = 6e7 S/m)
    R_C  = 2 * rho_C / (A_n + A_p)               # contact resistance (x2 interfaces)
    R_int = R_n + R_p + R_IC + R_C

    # Thermal conductance of both legs [W/K]
    K = k_n * A_n / H_TE + k_p * A_p / H_TE

    # Open-circuit Seebeck voltage and matched-load maximum power
    dT   = T_h - T_C
    V_oc = (abs(S_n) + abs(S_p)) * dT
    P_max = V_oc**2 / (4 * R_int)

    # Input heat flux (Fourier conduction + Peltier term at matched load)
    Q_in = K * dT + 0.5 * (abs(S_n) + abs(S_p)) * (V_oc / (2 * R_int)) * dT

    PD_max = (P_max / A_device) * 0.1          # convert W/m^2 → mW/cm^2
    eta    = (P_max / max(Q_in, 1e-12)) * 100  # [%]

    return float(max(PD_max, 0)), float(max(eta, 0))


